# -------------------------------------------------------- Fortran formats ---

def format_e(value, width, digits):
    """value in Fortran Ew.d format (0.ddddE+xx, right-aligned in width)."""
    if value == 0:
        mantissa, exponent = "0" * digits, 0
    else:
        mantissa, exponent = f"{abs(value):.{digits - 1}e}".split("e")
        mantissa, exponent = mantissa.replace(".", ""), int(exponent) + 1
    if abs(exponent) > 99:
        raise GeneratorError(f"{value} needs a three-digit exponent")
    text = f"{'-' if value < 0 else ''}0.{mantissa}E{exponent:+03d}"
    if len(text) > width:
        raise GeneratorError(f"{value} does not fit E{width}.{digits}")
    return text.rjust(width)


def parse_e_format(fmt):
    """'(nEw.d)' -> (n, w, d)."""
    m = re.fullmatch(r"\(\s*(\d+)E(\d+)\.(\d+)\s*\)", fmt.strip())
    if not m:
        raise GeneratorError(f"unsupported data format {fmt!r}: expected (nEw.d)")
    return tuple(int(g) for g in m.groups())


def format_e_records(values, n, width, digits):
    """values in (nEw.d) records: n values per line, the last line possibly shorter."""
    fields = [format_e(v, width, digits) for v in values]
    return "\n".join("".join(fields[i:i + n]) for i in range(0, len(fields), n))


def format_e14(values):
    """values as consecutive E14.5 fields (theory spectrum layout)."""
    return "".join(format_e(v, 14, 5) for v in values)


def format_int_line(values):
    """25I4 lines as written by viperleed's writeWEXPEL."""
    if any(not -1000 < v < 10000 for v in values):
        raise GeneratorError(f"values do not fit I4: {values}")
    out = "\n".join("".join(f"{v:4d}" for v in values[i:i + 25])
                    for i in range(0, len(values), 25)) + "\n"
    if len(values) % 25 == 0:
        out += "\n"
    return out


# ------------------------------------------------------------ WEXPEL edits ---

def set_beam_arrays(text, kav, nbea, ibp, mittel):
    """Replace the KAV/NBEA/IBP/MITTEL lines between &NL1 ... &END and &NL2."""
    lines = text.split("\n")
    i_end = next(i for i, l in enumerate(lines) if l.strip() == "&END")
    i_nl2 = next(i for i, l in enumerate(lines) if l.strip() == "&NL2")
    block = "".join(format_int_line(v) for v in (kav, nbea, ibp, mittel))
    return "\n".join(lines[:i_end + 1] + block.rstrip("\n").split("\n") + lines[i_nl2:])


def split_exp_data(text):
    """WEXPEL -> (head up to and incl. format line, format, [beams], tail).

    Each beam is (name_line, fac_line_rest, [(E, I), ...]).
    """
    lines = text.split("\n")
    i_fmt = next(i for i, l in enumerate(lines) if re.fullmatch(r"\s*\(.*E.*\)\s*", l))
    head = lines[:i_fmt + 1]
    fmt = lines[i_fmt].strip()
    _, width, _ = parse_e_format(fmt)
    beams, i = [], i_fmt + 1
    while i < len(lines) and lines[i].strip():
        name = lines[i]
        n, rest = int(lines[i + 1][:4]), lines[i + 1][4:]
        i += 2
        values = []
        while len(values) < 2 * n:
            fields = (lines[i][j:j + width] for j in range(0, len(lines[i]), width))
            values += [float(f) for f in fields if f.strip()]
            i += 1
        values = values[:2 * n]
        beams.append((name, rest, list(zip(values[0::2], values[1::2]))))
    return head, fmt, beams, lines[i:]


def join_exp_data(head, fmt, beams, tail):
    """Inverse of split_exp_data: assemble the experimental-data part from its pieces."""
    n, width, digits = parse_e_format(fmt)
    out = list(head)
    for name, rest, points in beams:
        out.append(name)
        out.append(f"{len(points):4d}{rest}")
        flat = [x for p in points for x in p]
        out += format_e_records(flat, n, width, digits).split("\n")
    return "\n".join(out + tail)


# -------------------------------------------------------------- benchmark ---

def beam_modulation(beam, energy):
    """Factor that makes the copies of the four Ag(100) beams differ from each other."""
    return 1.0 + 0.25 * math.sin(0.037 * energy * (beam + 1) + beam)


def make_many_beams(wexpel, spectrum, param, nexp, ntheo, ngeo):
    """(wexpel, spectrum, param) with nexp experimental and ntheo theory beams and
    ngeo geometries, made from the four beams and one geometry of the inputs.

    Beam k is a copy of beam k % 4 times beam_modulation; geometry g scales the
    theory beams by 1 + 0.01 g cos(0.1 E + k). The first nexp theory beams are
    matched to the experimental beams (KAV, NBEA, IBP), with MITTEL alternating
    between 1 and 2; the others are not used.
    """
    head, fmt, beams, tail = split_exp_data(wexpel)
    exp_beams = []
    for k in range(nexp):
        _, rest, points = beams[k % len(beams)]
        exp_beams.append((f"*({k:3d}  0)*", rest,
                          [(e, a * beam_modulation(k, e)) for e, a in points]))
    wexpel = set_beam_arrays(join_exp_data(head, fmt, exp_beams, tail),
                             [k + 1 if k < nexp else 0 for k in range(ntheo)],
                             list(range(1, nexp + 1)), list(range(1, nexp + 1)),
                             [1 + k % 2 if k < nexp else 0 for k in range(ntheo)])

    lines = spectrum.split("\n")
    nbeams = int(lines[1])
    if nbeams > 4:
        raise GeneratorError(f"{nbeams} theory beams: expected at most 4 (one line per energy)")
    out = [lines[0], f"{ntheo:5d}"]
    out += [f"{k + 1:5d}{1.0 + k:10.5f}{0.0:10.5f}{1:3d}" for k in range(ntheo)]
    for line in lines[2 + nbeams:]:
        if not line.strip():
            continue
        energy = float(line[:7])
        base = [float(line[14 + 14 * i:28 + 14 * i]) for i in range(nbeams)]
        for g in range(ngeo):
            values = [base[k % nbeams] * beam_modulation(k, energy)
                      * (1 + 0.01 * g * math.cos(0.1 * energy + k)) for k in range(ntheo)]
            out.append(f"{energy:7.2f}{0.0001 * (g + 1):7.4f}" + format_e14(values[:4]))
            rest = values[4:]
            out += [format_e14(rest[i:i + 5]) for i in range(0, len(rest), 5)]
            if len(rest) % 5 == 0:
                out.append("")
    nenergies = sum(1 for line in lines[2 + nbeams:] if line.strip())
    for key, value in (("MNBED", nexp), ("MNBTD", ntheo), ("MNET", nenergies + 3),
                       ("MNS", ngeo)):
        param, n = re.subn(rf"\b{key} = \d+", f"{key} = {value}", param)
        if n != 1:
            raise GeneratorError(f"expected one '{key} =' in PARAM, found {n}")
    return wexpel, "\n".join(out) + "\n", param


# ------------------------------------------------------------------ cases ---

def write_rfactor_case(name, description, covers, runs, cases_dir=RFACTOR_DIR, header=HEADER):
    """Write cases_dir/name (case.toml, inputs/) and return its directory.

    runs: [(run_name, wexpel_text, param_text, spectrum_text)]; the titles of
    the WEXPEL files and spectra become 'tl-test <name>', and identical PARAM
    and spectrum files are shared between runs.
    """
    title = f"tl-test {name}"
    inputs, toml_runs, written = {}, [], {}
    for run, wexpel, param, spectrum in runs:
        inputs[f"inputs/WEXPEL_{run}"] = set_wexpel_title(wexpel, title)
        spectrum = set_first_line_title(spectrum, title)
        for kind, content in (("PARAM", param), ("spectrum", spectrum)):
            key = (kind, content)
            if key not in written:
                fname = kind if not any(k[0] == kind for k in written) else f"{kind}_{run}"
                inputs[f"inputs/{fname}"] = content
                written[key] = fname
        toml_runs.append({
            "name": run,
            "stdin": f'inputs/{written[("spectrum", spectrum)]}',
            "param": f'inputs/{written[("PARAM", param)]}',
            "files": {"WEXPEL": f"inputs/WEXPEL_{run}"}, "outputs": OUTPUTS})
    case_dir = cases_dir / name
    write_case(case_dir, header, "rfactor", description, covers, toml_runs, inputs)
    return case_dir


def build_benchmark_case(cases_dir):
    """Write the benchmark case bench_ag100_rfactor into cases_dir and return its directory.

    Made from the committed ag100_rfactor inputs (see make_many_beams), with
    BENCHMARK_SIZE beams and geometries. Its case.toml is committed in
    BENCHMARK_DIR; the inputs are generated where they are used.
    """
    inputs = RFACTOR_DIR / "ag100_rfactor" / "inputs"
    nexp, ntheo, ngeo = BENCHMARK_SIZE
    wexpel, spectrum, param = make_many_beams((inputs / "WEXPEL_pendry").read_text(),
                                              (inputs / "spectrum").read_text(),
                                              (inputs / "PARAM").read_text(), *BENCHMARK_SIZE)
    return write_rfactor_case(
        "bench_ag100_rfactor",
        f"Ag(100)-derived rfactor with {nexp} experimental and {ntheo} theory beams, "
        f"{ngeo} geometries, benchmark",
        ["benchmark"], [(f"nb{nexp}_t{ntheo}_ns{ngeo}", wexpel, param, spectrum)],
        Path(cases_dir), BENCHMARK_HEADER)
