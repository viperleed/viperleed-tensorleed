"""Freeze tier-2 systems and generate their expected results.

For each system:
1. initialize with viperleed (RUN = 0; systems.py inputs and overrides, using
   the generator TL copy for phase shifts) and freeze the initialized inputs
   (PARAMETERS, annotated POSCAR, VIBROCC, PHASESHIFTS, IVBEAMS, EXPBEAMS.csv)
   plus DISPLACEMENTS into tests/tier2/systems/<name>/, with RUN = 1 5,
   N_CORES = 4, TL_IGNORE_CHECKSUM = True;
2. run viperleed calc -t <baseline> on a copy (reference calculation + error
   calculation, as tests/tier2/test_viperleed.py does) and write
   tests/tier2/systems/<name>/expected.toml (refcalc R and V0 shift, all
   error curves).

Usage (in an environment with viperleed installed):
    python -m generate.make_tier2_expected \
        [--only NAME ...] [--workroot DIR] [--skip-freeze] [--calibrate]

--calibrate runs the baseline with FORTRAN_COMP = 'gfortran -O0' and
'gfortran -O2 -march=native' and prints the largest deviations from
expected.toml (tier-2 tolerance calibration, see tests/README.md).
"""
import argparse
import shutil
import sys
from pathlib import Path

from .baseline_tree import BASELINE_COMMIT
from .make_refcalc_cases import (_viperleed_exe, ensure_generator_tl,
                                prepare_calc_dir, run_viperleed)
from .systems import SYSTEMS
from harness import tier2
from harness.paths import location

SYSTEMS_DIR = Path(__file__).parents[1] / "tier2" / "systems"

DISPLACEMENTS = {
    "ag100": ("= GEO_DELTA\n"
              "Ag L(1) z = -0.06 0.06 0.02\n"
              "Ag L(2) z = -0.06 0.06 0.02\n"
              "= VIB_DELTA\n"
              "Ag_surf = -0.02 0.02 0.01\n"),
    "ag100_mix": ("= OCC_DELTA\n"
                  "Ag_surf = Ag 0.5 0.9 0.1, Pd 0.5 0.1 0.1\n"),
    "ir100_2x1_o": ("= GEO_DELTA\n"
                    "O_ads z = -0.06 0.06 0.02\n"
                    "Ir_surf z = -0.06 0.06 0.02\n"
                    "= VIB_DELTA\n"
                    "O_ads = -0.02 0.02 0.01\n"),
}


def freeze(name, workroot, tl):
    """Initialize a system with viperleed (RUN = 0) and store its inputs for tier 2."""
    calc = workroot / f"tier2-{name}" / "init"
    prepare_calc_dir(SYSTEMS[name], calc)
    run_viperleed(calc, tl)  # RUN = 0
    target = SYSTEMS_DIR / name
    target.mkdir(parents=True, exist_ok=True)
    for f in tier2.INPUT_FILES:
        if f != "DISPLACEMENTS" and (calc / f).is_file():
            shutil.copy(calc / f, target / f)
    (target / "DISPLACEMENTS").write_text(DISPLACEMENTS[name])
    tier2.set_parameters(target / "PARAMETERS", {"RUN": "1 5", "N_CORES": "4",
                                                 "TL_IGNORE_CHECKSUM": "True"})


def make_expected(name, workroot, tl):
    """Run viperleed calc on a frozen system and store the results as expected.toml."""
    work = workroot / f"tier2-{name}" / "baseline-run"
    if work.exists():
        shutil.rmtree(work)
    res = tier2.run_viperleed_calc(SYSTEMS_DIR / name, tl, [str(_viperleed_exe())], work)
    version = tier2.viperleed_version([str(_viperleed_exe())])
    comment = (f"Generated by tests/generate/make_tier2_expected.py from baseline "
               f"{BASELINE_COMMIT} with {version}.\n"
               "Regenerate only as described in tests/README.md, 'Rules'.")
    (SYSTEMS_DIR / name / "expected.toml").write_text(tier2.to_toml(res, comment))
    return res


CALIBRATION_VARIANTS = {
    "O0": {"FORTRAN_COMP": "'gfortran -O0'",
           "FORTRAN_COMP post": "'-llapack -lpthread -lblas -fbacktrace'"},
    "O2-native": {"FORTRAN_COMP": "'gfortran -O2 -march=native'",
                  "FORTRAN_COMP post": "'-llapack -lpthread -lblas -fbacktrace'"},
}


def calibrate(name, workroot, tl):
    """Max deviations of compiler-flag variants from expected.toml."""
    import tomllib
    expected = tier2.from_toml(tomllib.loads((SYSTEMS_DIR / name / "expected.toml").read_text()))
    for variant, params in CALIBRATION_VARIANTS.items():
        work = workroot / f"tier2-{name}" / f"calib-{variant}"
        if work.exists():
            shutil.rmtree(work)
        res = tier2.run_viperleed_calc(SYSTEMS_DIR / name, tl,
                                       [str(_viperleed_exe())], work, params)
        dev_r = [abs(res["refcalc"]["r"] - expected["refcalc"]["r"])]
        dev_other = [abs(res["refcalc"]["v0_shift"] - expected["refcalc"]["v0_shift"])]
        for fname, cols in expected["errors"].items():
            for col, vals in cols.items():
                devs = [abs(a - e) for a, e in zip(res["errors"][fname][col], vals)]
                (dev_r if col == "R" else dev_other).extend(devs)
        print(f"calibration {name} [{variant}]: max |dR| = {max(dev_r):.1e}, "
              f"max |d other| = {max(dev_other):.1e}")


def main(argv=None):
    """Freeze the inputs and regenerate expected.toml of the tier-2 systems, or calibrate."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--only", nargs="+", choices=sorted(DISPLACEMENTS))
    parser.add_argument("--workroot", type=Path, default=None,
                        help="default: generate_workroot (tests/harness/paths.py)")
    parser.add_argument("--skip-freeze", action="store_true",
                        help="keep the frozen inputs, only regenerate expected.toml")
    parser.add_argument("--calibrate", action="store_true",
                        help="only compare compiler-flag variants with expected.toml")
    args = parser.parse_args(argv)
    args.workroot = args.workroot or location("generate_workroot")
    tl = ensure_generator_tl()
    if args.calibrate:
        for name in args.only or DISPLACEMENTS:
            calibrate(name, args.workroot, tl)
        return 0
    for name in args.only or DISPLACEMENTS:
        if not args.skip_freeze:
            freeze(name, args.workroot, tl)
        res = make_expected(name, args.workroot, tl)
        curves = {n: len(next(iter(c.values()))) for n, c in res["errors"].items()}
        print(f"{name}: R = {res['refcalc']['r']}, V0 shift = {res['refcalc']['v0_shift']}, "
              f"error curves {curves}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
