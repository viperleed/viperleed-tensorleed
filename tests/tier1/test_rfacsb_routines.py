import json
import subprocess
from pathlib import Path

import pytest

from harness.build import DEBUG, RELEASE

DATA = Path(__file__).with_name("rfacsb_routines")
CASES = json.loads((DATA / "values.json").read_text())["cases"]


@pytest.fixture(scope="module", params=[RELEASE, DEBUG], ids=lambda f: f.name)
def driver(request, tl_root, tmp_path_factory):
    """The driver executable built against the tree's lib/rfacsb.f90."""
    flags = request.param
    workdir = tmp_path_factory.mktemp(f"rfacsb-driver-{flags.name}")
    exe = workdir / "driver"
    proc = subprocess.run(["gfortran", *flags.compile.split(), "-std=f2018", "-w",
                           "-J", str(workdir), "-o", str(exe),
                           str(tl_root / "TensErLEED" / "lib" / "rfacsb.f90"),
                           str(DATA / "driver.f90")],
                          capture_output=True, text=True)
    if proc.returncode != 0:
        pytest.fail(f"driver build failed:\n{proc.stdout}{proc.stderr}")
    return exe


@pytest.mark.tier1
def test_values_hold_cases():
    """values.json holds input sets (without them the comparison below is skipped)."""
    assert CASES, f"no cases in {DATA / 'values.json'}"


@pytest.mark.tier1
@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_routine_matches_baseline_bits(case, driver):
    """The routine gives bit-identical results to the legacy routine on these inputs.

    Failing means the floating-point operations of the routine (or their order)
    changed; the message lists the differing elements (hex bit patterns)."""
    proc = subprocess.run([str(driver)], input="\n".join(case["stdin"]) + "\n",
                          capture_output=True, text=True)
    assert proc.returncode == 0, f"driver failed:\n{proc.stderr}"
    got = [line.strip().lower() for line in proc.stdout.splitlines()]
    expected = case["expected"]
    assert len(got) == len(expected), f"{len(got)} values, expected {len(expected)}"
    diffs = [f"element {i + 1}: {g} != {e}"
             for i, (g, e) in enumerate(zip(got, expected)) if g != e]
    assert not diffs, f"{case['covers']}:\n" + "\n".join(diffs)
