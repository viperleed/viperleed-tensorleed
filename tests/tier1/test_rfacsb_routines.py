"""Tier 1: single routines of lib/rfacsb.f90 compared bit for bit with the baseline.

rfacsb_routines/driver.f90 is compiled with gfortran against the tree's
lib/rfacsb.f90 (release and debug flags), run once per input set of
rfacsb_routines/values.json, and its results must equal the bits that the
legacy routines of the baseline produced on the same inputs (generated by
generate/make_rfacsb_routine_values.py). Covered: DER, SMOOTH and YSMOOTH
for curves of 1, 2 and 3 points and short curves, including the one-sided
end formulas of DER.
"""

