import json
import shlex
import subprocess
from pathlib import Path

import pytest

from harness.build import DEBUG, RELEASE, program_sources
from harness.routine_blocks import summarize

DATA = Path(__file__).with_name("refcalc_routines")
CASES = json.loads((DATA / "values.json").read_text())["cases"]


def _compile(cmd, workdir):
    """Run a compiler command in workdir; fail the test with its output on error."""
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=workdir)
    if proc.returncode != 0:
        pytest.fail(f"driver build failed ({shlex.join(cmd)}):\n{proc.stdout}{proc.stderr}")


@pytest.fixture(scope="module", params=[RELEASE, DEBUG], ids=lambda f: f.name)
def driver(request, tl_root, tmp_path_factory):
    """The driver executable built against the tree's sources of ref-calc: its
    free-form modules (in the order of the Makefile) and lib/lib.tleed.f."""
    flags = request.param
    workdir = tmp_path_factory.mktemp(f"refcalc-driver-{flags.name}")
    sources = program_sources(tl_root, "refcalc")
    modules = [src for src in sources if src.suffix == ".f90"]
    legacy = [src for src in sources if src.name == "lib.tleed.f"]
    objects = []
    for src in [*modules, DATA / "driver.f90"]:
        obj = workdir / f"{src.stem}.o"
        _compile(["gfortran", *flags.compile.split(), "-std=f2018", "-w", "-J", str(workdir),
                  "-c", "-o", str(obj), str(src)], workdir)
        objects.append(obj)
    for src in legacy:
        obj = workdir / f"{src.stem}.o"
        _compile(["gfortran", *flags.compile.split(), "-w", "-I", str(src.parents[1] / "src"),
                  "-c", "-o", str(obj), str(src)], workdir)
        objects.append(obj)
    exe = workdir / "driver"
    _compile(["gfortran", *flags.compile.split(), "-o", str(exe),
              *map(str, objects), *flags.link.split()], workdir)
    return exe


@pytest.mark.tier1
def test_values_hold_cases():
    """values.json holds input sets (without them the comparison below is skipped)."""
    assert CASES, f"no cases in {DATA / 'values.json'}"


@pytest.mark.tier1
@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_routines_match_baseline_bits(case, driver):
    """The routines give bit-identical results to the legacy routines on these inputs.

    Failing means the floating-point operations of a routine (or their order)
    changed; the message names the differing arrays and, where the leading
    values differ, the first differing one (hex bit patterns or integers)."""
    proc = subprocess.run([str(driver)], input="\n".join(case["stdin"]) + "\n",
                          capture_output=True, text=True)
    assert proc.returncode == 0, f"driver failed:\n{proc.stderr}"
    got = summarize(proc.stdout)
    expected = case["expected"]
    assert list(got) == list(expected), f"arrays {list(got)}, expected {list(expected)}"
    diffs = []
    for name, want in expected.items():
        have = got[name]
        if have == want:
            continue
        if have["n"] != want["n"]:
            diffs.append(f"{name}: {have['n']} values, expected {want['n']}")
            continue
        first = next((i for i, (g, e) in enumerate(zip(have["head"], want["head"]))
                      if g != e), None)
        where = (f"element {first + 1}: {have['head'][first]} != {want['head'][first]}"
                 if first is not None else "beyond the leading values (digest differs)")
        diffs.append(f"{name}: {where}")
    assert not diffs, f"{case['covers']}:\n" + "\n".join(diffs)
