DATA = Path(__file__).with_name("refcalc_routines")
CASES = json.loads((DATA / "values.json").read_text())["cases"]

# Cases on which the routines stop with a message that starts with this text
# on stderr, where the legacy routines gave a result that ref-calc then used
# wrongly: SLIND with an IDEG that does not fit the lattices (legacy
# JJS = NL + 1, which indexes past FLMS in FMAT)
STOPS = {
    "slind_square_p2x2_ideg3": "IDEG = 3 does not fit",
    }
COMPARED = [c for c in CASES if c["id"] not in STOPS]
STOPPING = [c for c in CASES if c["id"] in STOPS]
# flags of the legacy driver for the live cases (the generator checks that
# all of its flag sets give the same results)
LEGACY_FLAGS = FLAG_SETS[0]
NO_BASELINE_MSG = ("the live cases of refcalc_routines/values.json compare with the "
                   "legacy routines of the baseline tree: pass --baseline-tl-root=<tree> "
                   "or set baseline_tl_root (tests/local.toml) or TL_TEST_BASELINE")


def _compile(cmd, workdir):
    """Run a compiler command in workdir; fail the test with its output on error."""
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=workdir)
    if proc.returncode != 0:
        pytest.fail(f"driver build failed ({shlex.join(cmd)}):\n{proc.stdout}{proc.stderr}")


@pytest.fixture(scope="module", params=[RELEASE, DEBUG], ids=lambda f: f.name)
def driver(request, tl_root, tmp_path_factory):
    """The driver executable built against the tree's sources of ref-calc: its
    free-form modules (in the order of the Makefile) and lib/lib.tleed.f."""
    flags = request.param
    workdir = tmp_path_factory.mktemp(f"refcalc-driver-{flags.name}")
    sources = program_sources(tl_root, "refcalc")
    modules = [src for src in sources if src.suffix == ".f90"]
    legacy = [src for src in sources if src.name == "lib.tleed.f"]
    objects = []
    for src in [*modules, DATA / "driver.f90"]:
        obj = workdir / f"{src.stem}.o"
        _compile(["gfortran", *flags.compile.split(), "-std=f2018", "-w", "-J", str(workdir),
                  "-c", "-o", str(obj), str(src)], workdir)
        objects.append(obj)
    for src in legacy:
        obj = workdir / f"{src.stem}.o"
        _compile(["gfortran", *flags.compile.split(), "-w", "-I", str(src.parents[1] / "src"),
                  "-c", "-o", str(obj), str(src)], workdir)
        objects.append(obj)
    exe = workdir / "driver"
    _compile(["gfortran", *flags.compile.split(), "-o", str(exe),
              *map(str, objects), *flags.link.split()], workdir)
    return exe


@pytest.fixture(scope="session")
def legacy_driver(request):
    """The legacy driver of the generator, built from the baseline tree's
    lib.tleed.f with LEGACY_FLAGS (cached in tests/.build-cache; the key
    covers the driver's sources and the generator file with its build recipe)."""
    if not (request.config.getoption("--baseline-tl-root")
            or configured("baseline_tl_root")):
        pytest.fail(NO_BASELINE_MSG, pytrace=False)
    tl = request.getfixturevalue("baseline_tl_root")
    try:
        check_baseline_tree(tl)
    except GeneratorError as err:
        pytest.fail(f"--baseline-tl-root / baseline_tl_root: {err}", pytrace=False)
    lib = tl / "TensErLEED"
    # the generator's file holds the build recipe (build_legacy_driver)
    recipe = Path(make_refcalc_routine_values.__file__)
    entry = cached_dir("refcalc-legacy-driver",
                       [lib / "lib" / "lib.tleed.f", lib / "src" / "GLOBAL", LEGACY_DRIVER,
                        recipe],
                       lib, LEGACY_FLAGS,
                       lambda tmp: build_legacy_driver(tl, tmp, LEGACY_FLAGS))
    return entry / f"legacy{LEGACY_FLAGS}"


def _expected(case, request):
    """The legacy results of case: stored in values.json, or for a live case
    from the legacy driver of the baseline (fixture legacy_driver)."""
    if not case.get("live"):
        return case["expected"]
    expected = run_legacy_driver(request.getfixturevalue("legacy_driver"), case["stdin"])
    # an empty legacy output would let an empty port output pass
    assert expected, f"{case['id']}: the legacy driver printed no arrays"
    return expected


@pytest.mark.tier1
def test_values_hold_cases():
    """values.json holds input sets (without them the comparison below is skipped)."""
    assert CASES, f"no cases in {DATA / 'values.json'}"


@pytest.mark.tier1
@pytest.mark.parametrize("case", COMPARED, ids=[c["id"] for c in COMPARED])
def test_routines_match_baseline_bits(case, driver, request):
    """The routines give bit-identical results to the legacy routines on these inputs.

    Failing means the floating-point operations of a routine (or their order)
    changed; the message names the differing arrays and, where the leading
    values differ, the first differing one (hex bit patterns or integers).
    Live cases need the baseline tree (fixture legacy_driver)."""
    proc = subprocess.run([str(driver)], input="\n".join(case["stdin"]) + "\n",
                          capture_output=True, text=True)
    assert proc.returncode == 0, f"driver failed:\n{proc.stderr}"
    got = summarize(proc.stdout)
    expected = _expected(case, request)
    assert list(got) == list(expected), f"arrays {list(got)}, expected {list(expected)}"
    diffs = []
    for name, want in expected.items():
        have = got[name]
        if have == want:
            continue
        if have["n"] != want["n"]:
            diffs.append(f"{name}: {have['n']} values, expected {want['n']}")
            continue
        first = next((i for i, (g, e) in enumerate(zip(have["head"], want["head"]))
                      if g != e), None)
        where = (f"element {first + 1}: {have['head'][first]} != {want['head'][first]}"
                 if first is not None else "beyond the leading values (digest differs)")
        diffs.append(f"{name}: {where}")
    assert not diffs, f"{case['covers']}:\n" + "\n".join(diffs)


@pytest.mark.tier1
def test_stopping_cases_are_in_values():
    """Every case of STOPS is an input set of values.json."""
    assert len(STOPPING) == len(STOPS), f"not in values.json: {set(STOPS) - {c['id'] for c in CASES}}"


@pytest.mark.tier1
@pytest.mark.parametrize("case", STOPPING, ids=[c["id"] for c in STOPPING])
def test_routines_stop_where_legacy_result_is_invalid(case, driver):
    """The routines stop with a non-zero exit code and a message on stderr that starts with STOPS.

    Failing means the check of an input the legacy routines handled wrongly
    is gone, or reports another message."""
    proc = subprocess.run([str(driver)], input="\n".join(case["stdin"]) + "\n",
                          capture_output=True, text=True, timeout=RUN_TIMEOUT_S)
    assert proc.returncode != 0, f"exit code 0; stdout:\n{proc.stdout}"
    assert proc.stderr.startswith("ref-calc: " + STOPS[case["id"]]), proc.stderr
