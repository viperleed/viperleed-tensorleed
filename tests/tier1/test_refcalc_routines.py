"""Tier 1: single routines of ref-calc compared bit for bit with the baseline.

refcalc_routines/driver.f90 is compiled with gfortran against the tree's
sources of ref-calc (release and debug flags), run once per input set of
refcalc_routines/values.json, and its results must equal those that the
legacy routines of the baseline produced on the same inputs (generated by
generate/make_refcalc_routine_values.py). Covered: the Clebsch-Gordan
and Gaunt tables CAA, CLM and PPP, the permutations LX, LXI, LT and LXM for
every LMAX from 2 to 18, and the sublattice tables V, VL and JJS of SLIND
for several lattices; TSCATF (with PSTEMP and BESSEL) and the average of its
results over the elements of a site; BEAMS; SPHRM_MOD; FMAT; and BEAMS, FMAT
and RSMF_SIMPLE (with XM and MFOLD_SIMPLE) chained as in ref-calc. Large
arrays are compared by a digest of their bits and their leading values.
For the cases in STOPS the routines stop with an error instead; their
values in values.json record what the legacy routines gave.

The cases marked live in values.json (those of RSMF_SIMPLE, whose legacy
results depend on the BLAS/LAPACK the program runs with) have no stored
values: the legacy driver of the generator is built from the baseline tree
(--baseline-tl-root or baseline_tl_root; it must be at the baseline commit)
and run on the same inputs, with the same BLAS/LAPACK, at test time.
"""

