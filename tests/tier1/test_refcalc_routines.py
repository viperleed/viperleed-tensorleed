"""Tier 1: single routines of ref-calc compared bit for bit with the baseline.

refcalc_routines/driver.f90 is compiled with gfortran against the tree's
sources of ref-calc (release and debug flags), run once per input set of
refcalc_routines/values.json, and its results must equal those that the
legacy routines of the baseline produced on the same inputs (generated by
generate/make_refcalc_routine_values.py). Covered: the Clebsch-Gordan
and Gaunt tables CAA, CLM and PPP, the permutations LX, LXI, LT and LXM for
every LMAX from 2 to 18, and the sublattice tables V, VL and JJS of SLIND
for several lattices. Large arrays are compared by a digest of their bits
and their leading values.
"""

